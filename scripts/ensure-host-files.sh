#!/usr/bin/env bash
# Ensure the two host files that docker-compose.yml bind-mounts INDIVIDUALLY
# exist before the stack comes up.
#
# Why this has to exist at all:
#
# The api container needs to write exactly two files on the host —
# libraries.conf and docker-compose.override.yml — because the Settings UI can
# add and remove extra library mounts. It used to get that by bind-mounting the
# entire project root read-write, which handed the container .git, .env, and
# every source file. docker-compose.yml now mounts the root read-only and adds
# those two files back individually as :rw.
#
# The catch is that a per-file bind mount REQUIRES its source to exist. Docker
# does not error when a bind-mount source is missing — it silently creates a
# DIRECTORY at that path. For docker-compose.override.yml that is actively
# destructive: compose auto-loads that filename from the repo root, so the next
# `docker compose` invocation tries to parse a directory as YAML and the whole
# stack refuses to start, with an error that points nowhere near the cause.
#
# Both files are in .gitignore (they hold machine-specific host paths), so a
# fresh clone has NEITHER. setup.sh creates them, but README documents raw
# `docker compose up` too, and ./pillar43 and `make` are the paths people
# actually use day to day. Hence one idempotent guard, called from all of them.
#
# Safe to run any time: it only ever creates a missing file, never touches one
# that already exists.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

fail_if_dir() {
  if [[ -d "$1" ]]; then
    echo "error: $1 is a directory, but it must be a file." >&2
    echo "  Docker creates a directory when a bind-mount source is missing." >&2
    echo "  Remove it and re-run:  rmdir '$1'" >&2
    exit 1
  fi
}

CONF="$ROOT/libraries.conf"
OVERRIDE="$ROOT/docker-compose.override.yml"

fail_if_dir "$CONF"
fail_if_dir "$OVERRIDE"

if [[ ! -f "$CONF" ]]; then
  cat > "$CONF" <<'EOF'
# Extra read-only libraries, one per line, as:  name = /absolute/host/path
# Add them here and run scripts/gen-libraries-override.sh, or use the
# Settings UI, which does both for you.
EOF
  echo "Created libraries.conf"
fi

if [[ ! -f "$OVERRIDE" ]]; then
  cat > "$OVERRIDE" <<'EOF'
# Auto-generated by scripts/ensure-host-files.sh — do not edit directly.
# No extra libraries are configured, so this file deliberately declares
# nothing. It is left in place rather than deleted because it is a
# bind-mounted FILE: a container cannot unlink one (EBUSY), and if it is
# missing when the stack comes up Docker silently creates a DIRECTORY at
# that path instead. Add a library and this file is rewritten with mounts.
EOF
  echo "Created docker-compose.override.yml (inert — no libraries configured)"
fi
