#!/usr/bin/env bash
# Generate docker-compose.override.yml from libraries.conf.
# Each "name = /path" entry becomes its own read-only bind mount at /libraries/<name>.
# Run after editing libraries.conf, then: docker compose up --build -d

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$SCRIPT_DIR/.."
CONF="$ROOT/libraries.conf"
OUT="$ROOT/docker-compose.override.yml"

declare -a NAMES
declare -a PATHS

if [[ -f "$CONF" ]]; then
  while IFS= read -r line; do
    [[ "$line" =~ ^[[:space:]]*# ]] && continue
    [[ "$line" =~ ^[[:space:]]*$ ]] && continue
    if [[ "$line" =~ ^[[:space:]]*([a-zA-Z0-9_-]+)[[:space:]]*=[[:space:]]*(.+)[[:space:]]*$ ]]; then
      NAMES+=("${BASH_REMATCH[1]}")
      # trim trailing whitespace from path
      path="${BASH_REMATCH[2]}"
      path="${path%"${path##*[![:space:]]}"}"
      PATHS+=("$path")
    fi
  done < "$CONF"
fi

# Empty the override rather than deleting it. It is bind-mounted into the api
# container as a FILE; a container cannot unlink a bind-mounted file (EBUSY),
# and if the path is missing when the stack starts, Docker silently creates a
# DIRECTORY there instead. Kept in step with api/services/libraries_config.py,
# which does the same thing for the in-process path the Settings UI calls.
if [[ ${#NAMES[@]} -eq 0 ]]; then
  cat > "$OUT" <<'INERT'
# Auto-generated by scripts/gen-libraries-override.sh — do not edit directly.
# No extra libraries are configured, so this file deliberately declares
# nothing. It is left in place rather than deleted because it is a
# bind-mounted FILE: a container cannot unlink one (EBUSY), and if it is
# missing when the stack comes up Docker silently creates a DIRECTORY at
# that path instead. Add a library and this file is rewritten with mounts.
INERT
  echo "No libraries configured — docker-compose.override.yml emptied."
  exit 0
fi

{
  echo "# Auto-generated by scripts/gen-libraries-override.sh — do not edit directly."
  echo "# Update libraries.conf and re-run this script, then: docker compose up --build -d"
  echo "services:"
  echo "  api:"
  echo "    volumes:"
  for i in "${!NAMES[@]}"; do
    echo "      - ${PATHS[$i]}:/libraries/${NAMES[$i]}:ro"
  done
  # No `worker:` block — that service was folded into the API (2026-08-18).
  # Emitting one would merge into an image-less service and fail the stack.
} > "$OUT"

count=${#NAMES[@]}
echo "Generated docker-compose.override.yml with $count librar$([ "$count" -eq 1 ] && echo 'y' || echo 'ies'): ${NAMES[*]}"
